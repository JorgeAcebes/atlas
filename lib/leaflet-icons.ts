function escapeHtml(text: string): string {
  return text
    .replace(/&/g, "&amp;")
    .replace(/</g, "&lt;")
    .replace(/>/g, "&gt;")
    .replace(/"/g, "&quot;")
    .replace(/'/g, "&#39;");
}

function renderExperienceInnerHtml(name: string, size = 18): string {
  if (name && /\p{Extended_Pictographic}/u.test(name)) {
    return `<span style="font-size:${size}px;line-height:1;display:inline-flex;align-items:center;justify-content:center">${escapeHtml(name)}</span>`;
  }
  const inner = ICON_SVG_INNER[name] || ICON_SVG_INNER.star;
  return `<svg viewBox="0 0 24 24" width="${size}" height="${size}" fill="none" stroke="currentColor" stroke-width="2" stroke-linecap="round" stroke-linejoin="round" aria-hidden="true">${inner}</svg>`;
}

const expIconCache = new Map<string, L.DivIcon>();

/**
 * Pure-string DivIcon generator for experiences (zero react-dom/server runtime cost).
 */
export function getExperienceIcon(iconName: string): L.DivIcon {
  const key = iconName || "star";
  const cached = expIconCache.get(key);
  if (cached) return cached;

  const html = `<div style="width:100%;height:100%;display:flex;justify-content:center;align-items:center"><span class="summit-pin summit-pin--experience summit-pin--done" style="display:inline-flex;justify-content:center;align-items:center;pointer-events:none">${renderExperienceInnerHtml(key, 18)}</span></div>`;
  const icon = L.divIcon({
    className: "experience-hitbox",
    html,
    iconSize: [36, 36],
    iconAnchor: [18, 18],
  });
  expIconCache.set(key, icon);
  return icon;
}

